"""Section summaries, generated on first request (IP-030 §4; replaces IP-024's chapter summaries).

A section is a distinct `Paragraph.section` heading of the active extraction run (`extraction.outline`). Its
80-120 word summary and 3-8 concepts are generated the first time a reader asks for it (`study(summary)`), or
ahead of time for popular books (`manage.py summarise_sections`), and kept while the section's text and the
prompt stay the same (`SectionSummary.digest`). "Summarise this chapter" took 3 minutes on 2026-11-12; the next
reader of that section gets it at once. The concepts feed the AGE graph (`graph.projection.project_concepts`).

On CPU a section costs a prompt evaluation of up to ~2.5K tokens (the text is cut at `MAX_SECTION_CHARS`).
Publications lent through Readium LCP are never summarised: their text never reaches the model (IP-018 Q5), and a
summary would carry it to every reader who can see the record.
"""

import hashlib
import logging
from typing import Dict, List, Optional

from django.conf import settings

from apps.assistant import prompts, structured

logger = logging.getLogger(__name__)

SYSTEM_PROMPT = prompts.render("section_summary")

SUMMARY_SCHEMA = {
    "type": "object",
    "properties": {
        "summary": {"type": "string"},
        "concepts": {
            "type": "array",
            "items": {
                "type": "object",
                "properties": {
                    "term": {"type": "string"},
                    "role": {"type": "string", "enum": ["defines", "discusses"]},
                },
                "required": ["term", "role"],
            },
        },
    },
    "required": ["summary", "concepts"],
}

#: Characters of a section given to the model.
MAX_SECTION_CHARS = 8000

#: Text shorter than this is not worth a model call (a part title page, an empty section).
MIN_SECTION_CHARS = 300

#: Concepts kept per section.
MAX_CONCEPTS = 8

#: Sections listed in `get_entry` at most (one line each, with a summary where there is one).
MAX_SECTIONS_SHOWN = 30

#: Said once with the summaries, so the model treats them as orientation, not as the book's words.
SUMMARY_NOTE = "Section summaries are generated by the assistant from the text and unchecked; cite passages, not them."


def section_text(run, section: str) -> str:
    parts, size = [], 0
    for text in run.paragraphs.filter(section=section).order_by("seq").values_list("text", flat=True):
        parts.append(" ".join(text.split()))
        size += len(parts[-1])
        if size >= MAX_SECTION_CHARS:
            break
    return " ".join(parts)[:MAX_SECTION_CHARS]


def digest(text: str) -> str:
    return hashlib.sha256(f"{SYSTEM_PROMPT}\x00{text}".encode("utf-8")).hexdigest()


def _valid(value: dict) -> bool:
    return isinstance(value.get("summary"), str)


def summarise(client, section: str, text: str, book=None) -> tuple:
    """`(summary or None, concepts, tokens)` for one section. `book(delta)` records the model time (Q2)."""
    messages = [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": f'Section: "{section}"\n\nText:\n"""\n{text}\n"""'},
    ]
    content, tokens = "", 0
    for delta in client.chat(messages, tools=None, response_format=SUMMARY_SCHEMA):
        content += delta.content
        if book is not None:
            book(delta)
        if delta.done:
            tokens = delta.total_tokens
    data = structured.parse_object(content, _valid)
    if not data:
        return None, [], tokens
    concepts = []
    for item in data.get("concepts") or []:
        if isinstance(item, dict) and str(item.get("term") or "").strip():
            role = "defines" if item.get("role") == "defines" else "discusses"
            concepts.append({"term": " ".join(str(item["term"]).split())[:120], "role": role})
    return (" ".join(data["summary"].split()) or None), concepts[:MAX_CONCEPTS], tokens


def summary_for(run, entry, section, client=None, force: bool = False, book=None):
    """The section's current summary, generated now if it has none; None when the text is too short or it failed."""
    from apps.assistant.models import SectionSummary

    if entry.read_config("readium_enabled"):
        SectionSummary.objects.filter(entry=entry).delete()
        return None
    text = section_text(run, section.title)
    if len(text) < MIN_SECTION_CHARS:
        return None
    text_digest = digest(text)
    current = SectionSummary.objects.filter(run=run, section=section.title).first()
    if current is not None and not force and (current.digest == text_digest or current.digest == ""):
        # An empty digest is a chapter summary migrated from IP-024: kept until the next forced run.
        return current
    if client is None:
        from apps.assistant.llm import client as make_client

        client = make_client()
    try:
        summary, concepts, tokens = summarise(client, section.title, text, book)
    except Exception:
        logger.exception("Section summary failed: run %s section %r", run.pk, section.title[:60])
        return current
    if not summary:
        return current
    row, _created = SectionSummary.objects.update_or_create(
        run=run,
        section=section.title,
        defaults={
            "entry": entry,
            "first_page": section.first_page,
            "last_page": section.last_page,
            "summary": summary,
            "concepts": concepts,
            "digest": text_digest,
            "model": getattr(client, "model", "") or "",
            "tokens_used": tokens,
        },
    )
    try:
        from apps.graph import projection

        projection.project_concepts(row)
    except Exception:
        logger.exception("Could not project the concepts of section summary %s", row.pk)
    return row


def summarise_entry(entry_id, client=None, force: bool = False, limit: Optional[int] = None) -> Dict[str, int]:
    """Summarise the sections of one publication that have no current summary (the warm-up batch)."""
    from apps.assistant.models import SectionSummary
    from apps.core.models import Entry
    from apps.extraction.discovery import _entry_run
    from apps.extraction.outline import outline

    report = {"sections": 0, "summarised": 0, "kept": 0, "skipped": 0, "failed": 0}
    entry = Entry.objects.filter(pk=entry_id).first()
    if entry is None:
        return report
    if entry.read_config("readium_enabled"):
        SectionSummary.objects.filter(entry=entry).delete()
        report["skipped"] = 1
        return report
    run = _entry_run(entry.pk)
    sections = outline(run)
    report["sections"] = len(sections)
    for section in sections[:limit] if limit else sections:
        before = SectionSummary.objects.filter(run=run, section=section.title).values_list("digest", flat=True).first()
        row = summary_for(run, entry, section, client=client, force=force)
        if row is None:
            if len(section_text(run, section.title)) >= MIN_SECTION_CHARS:
                report["failed"] += 1
            continue
        report["kept" if before == row.digest and not force else "summarised"] += 1
    return report


def outline_for_model(entry_id, table_of_contents: Optional[List[dict]], readable: bool = False) -> dict:
    """What `get_entry` shows of a publication's structure.

    The table of contents as catalogued when there is one; else the sections of its processed text, each with
    its pages and, where generated, its summary — only when `readable` (`discovery._may_read_text` for this
    reader): section headings are part of the text, so never for Readium LCP nor outside the IP ranges.
    """
    from apps.assistant.models import SectionSummary
    from apps.core.models import Entry
    from apps.extraction.discovery import _entry_run
    from apps.extraction.outline import outline

    shown: dict = {"table_of_contents": table_of_contents} if table_of_contents else {}
    if not readable:
        return shown
    entry = Entry.objects.filter(pk=entry_id).first()
    if entry is None or entry.read_config("readium_enabled") or table_of_contents:
        return shown
    run = _entry_run(entry.pk)
    sections = outline(run)
    if not sections:
        return shown
    summaries = dict(SectionSummary.objects.filter(run=run).values_list("section", "summary"))
    lines = []
    for section in sections[:MAX_SECTIONS_SHOWN]:
        line = {"section": section.title[:120], "pages": f"{section.first_page}-{section.last_page}"}
        if summaries.get(section.title):
            line["summary"] = summaries[section.title]
        lines.append(line)
    shown["sections"] = lines
    if len(sections) > MAX_SECTIONS_SHOWN:
        shown["sections_note"] = f"{len(sections)} sections; study(outline) lists them all."
    if summaries:
        shown["summaries_note"] = SUMMARY_NOTE
    return shown


def model_name() -> str:
    from apps.assistant.llm import LLAMA_SERVER, backend

    if backend() == LLAMA_SERVER:
        return settings.EVILFLOWERS_ASSISTANT_LLAMA_MODEL or ""
    return settings.EVILFLOWERS_ASSISTANT_OLLAMA_MODEL or ""
